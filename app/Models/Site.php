<?php

namespace App\Models;

use App\Enums\Locale;
use App\Enums\SiteStatus;
use App\Models\Concerns\HasLocalizedFields;
use App\Support\Palette;
use App\Support\PreviewUrl;
use Illuminate\Database\Eloquent\Builder;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\Relations\HasMany;
use Illuminate\Database\Eloquent\Relations\HasManyThrough;
use Illuminate\Database\Eloquent\Relations\HasOne;
use Illuminate\Database\Eloquent\SoftDeletes;

class Site extends Model
{
    use HasFactory, HasLocalizedFields, SoftDeletes;

    protected $fillable = [
        'slug', 'status', 'company_name_ar', 'company_name_en', 'industry_id', 'template',
        'short_description', 'source_url', 'source_data', 'logo_path', 'logo_nobg_path', 'palette', 'font_key',
        'phone', 'whatsapp', 'email', 'address_ar', 'address_en', 'map_url', 'socials', 'seo',
        'default_locale', 'preloader_enabled', 'notify_enabled',
        'sent_at', 'first_viewed_at', 'last_viewed_at', 'views_count',
    ];

    protected $attributes = [
        'status' => 'draft',
        'template' => 'industrial',
        'default_locale' => 'ar',
        'preloader_enabled' => true,
        'notify_enabled' => true,
        'views_count' => 0,
    ];

    protected function casts(): array
    {
        return [
            'status' => SiteStatus::class,
            'default_locale' => Locale::class,
            'palette' => 'array',
            'socials' => 'array',
            'seo' => 'array',
            'source_data' => 'array',
            'preloader_enabled' => 'boolean',
            'notify_enabled' => 'boolean',
            'sent_at' => 'datetime',
            'first_viewed_at' => 'datetime',
            'last_viewed_at' => 'datetime',
            'views_count' => 'integer',
        ];
    }

    protected static function booted(): void
    {
        // keep generated shades in sync with the base colours (used by export / templates)
        static::saving(function (Site $site) {
            if ($site->isDirty('palette') && is_array($site->palette)) {
                $site->palette = Palette::withShades($site->palette) ?: null;
            }
        });
    }

    // ---------------------------------------------------------------- relations

    public function industry(): BelongsTo
    {
        return $this->belongsTo(Industry::class);
    }

    public function pages(): HasMany
    {
        return $this->hasMany(Page::class)->orderBy('sort')->orderBy('id');
    }

    public function homePage(): HasOne
    {
        return $this->hasOne(Page::class)->where('is_home', true);
    }

    public function sections(): HasManyThrough
    {
        return $this->hasManyThrough(Section::class, Page::class);
    }

    public function navItems(): HasMany
    {
        return $this->hasMany(NavItem::class)->orderBy('sort')->orderBy('id');
    }

    /** Top-level nav items with their (one level of) children. */
    public function menu(): HasMany
    {
        return $this->navItems()->whereNull('parent_id')->with('children');
    }

    public function aiRuns(): HasMany
    {
        return $this->hasMany(AiRun::class)->latest('id');
    }

    /** SEO meta for a locale (generated by AI, editable), with null fallbacks. */
    public function seo(Locale|string|null $locale = null): array
    {
        $locale = $locale instanceof Locale ? $locale->value : ($locale ?: app()->getLocale());

        return [
            'title' => $this->seo["title_{$locale}"] ?? null,
            'description' => $this->seo["description_{$locale}"] ?? null,
        ];
    }

    public function media(): HasMany
    {
        return $this->hasMany(Media::class);
    }

    public function visits(): HasMany
    {
        return $this->hasMany(Visit::class);
    }

    // ------------------------------------------------------------------- scopes

    /** Sites that can be served on their subdomain. */
    public function scopeServable(Builder $query): void
    {
        $query->where('status', '!=', SiteStatus::Archived->value);
    }

    // ------------------------------------------------------------------ helpers

    public function name(Locale|string|null $locale = null): ?string
    {
        return $this->localized('company_name', $locale);
    }

    public function address(Locale|string|null $locale = null): ?string
    {
        return $this->localized('address', $locale);
    }

    public function host(): string
    {
        return PreviewUrl::host($this->slug);
    }

    public function url(?Locale $locale = null, ?string $pageSlug = null): string
    {
        return PreviewUrl::to($this->slug, $locale, $pageSlug);
    }

    public function whatsappLink(?string $text = null): ?string
    {
        $digits = preg_replace('/\D+/', '', (string) $this->whatsapp);

        if ($digits === '') {
            return null;
        }

        return 'https://wa.me/'.$digits.($text ? '?text='.rawurlencode($text) : '');
    }

    public function phoneLink(): ?string
    {
        $phone = preg_replace('/[^\d+]+/', '', (string) $this->phone);

        return $phone === '' ? null : 'tel:'.$phone;
    }

    /** Palette value with industry → hard-coded fallback. */
    public function color(string $key): ?string
    {
        return $this->palette[$key]
            ?? $this->industry?->default_palette[$key]
            ?? null;
    }
}
